#!/usr/bin/env node
/**
 * gen-redirect-map.mjs: build the must-use plugin's old-URL map (PLAN §5.6).
 *
 * Reads  research/redirects.csv            (old_path,status,target,rule,…)
 *        wordpress/tools/redirects/repoint.csv (d15_target,b_target,note)
 * Writes wordpress/mu-plugins/spokares-hardening/redirect-map.php
 *        'path?sorted-query' => [ status, target ]
 *
 * Rows: 301 → the D15 target re-pointed to Option B's pages; 410 → 410
 * (both roster URLs included); none/keep → nothing (WordPress's 404, or the
 * page itself); host:… rows are DNS/panel work and are skipped.
 *
 * Node standard library only. Run from anywhere:
 *   node wordpress/tools/redirects/gen-redirect-map.mjs [--check]
 * --check prints what would change and exits 1 if the file is out of date.
 * Never deployed (tools/ stays out of every release).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname( fileURLToPath( import.meta.url ) );
const repo = path.resolve( here, '../../..' );
const csvPath = path.join( repo, 'research/redirects.csv' );
const repointPath = path.join( here, 'repoint.csv' );
const outPath = path.join( repo, 'wordpress/mu-plugins/spokares-hardening/redirect-map.php' );
const check = process.argv.includes( '--check' );

/** Minimal RFC 4180 CSV parser (quotes, doubled quotes, commas and newlines in quotes). */
function parseCsv( text ) {
	const rows = [];
	let row = [];
	let field = '';
	let quoted = false;
	for ( let i = 0; i < text.length; i++ ) {
		const c = text[ i ];
		if ( quoted ) {
			if ( c === '"' && text[ i + 1 ] === '"' ) {
				field += '"';
				i++;
			} else if ( c === '"' ) {
				quoted = false;
			} else {
				field += c;
			}
		} else if ( c === '"' ) {
			quoted = true;
		} else if ( c === ',' ) {
			row.push( field );
			field = '';
		} else if ( c === '\n' || c === '\r' ) {
			if ( c === '\r' && text[ i + 1 ] === '\n' ) {
				i++;
			}
			row.push( field );
			rows.push( row );
			row = [];
			field = '';
		} else {
			field += c;
		}
	}
	if ( field !== '' || row.length ) {
		row.push( field );
		rows.push( row );
	}
	const [ head, ...body ] = rows.filter( ( r ) => r.length > 1 || r[ 0 ] !== '' );
	return body.map( ( r ) => Object.fromEntries( head.map( ( h, i ) => [ h.trim(), ( r[ i ] ?? '' ).trim() ] ) ) );
}

/** Same as the PHP side: decode the path; sort the decoded query pairs. */
function keyOf( oldPath ) {
	const q = oldPath.indexOf( '?' );
	const rawPath = q === -1 ? oldPath : oldPath.slice( 0, q );
	const rawQuery = q === -1 ? '' : oldPath.slice( q + 1 );
	let p;
	try {
		p = decodeURIComponent( rawPath );
	} catch {
		p = rawPath;
	}
	const pairs = rawQuery.split( '&' ).filter( Boolean ).map( ( x ) => {
		try {
			return decodeURIComponent( x.replace( /\+/g, ' ' ) );
		} catch {
			return x;
		}
	} );
	pairs.sort();
	return pairs.length ? `${ p }?${ pairs.join( '&' ) }` : p;
}

function phpString( s ) {
	return "'" + s.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) + "'";
}

const rows = parseCsv( fs.readFileSync( csvPath, 'utf8' ) );
const repoint = new Map( parseCsv( fs.readFileSync( repointPath, 'utf8' ) ).map( ( r ) => [ r.d15_target, r.b_target ] ) );

const map = new Map();
const problems = [];
const counts = { 301: 0, 410: 0, skipped: 0 };
for ( const r of rows ) {
	const old = r.old_path;
	if ( ! old || old.startsWith( 'host:' ) || ! old.startsWith( '/' ) ) {
		counts.skipped++;
		continue;
	}
	if ( r.status === '410' ) {
		map.set( keyOf( old ), [ 410, '' ] );
		counts[ 410 ]++;
	} else if ( r.status === '301' ) {
		const target = repoint.get( r.target );
		if ( ! target ) {
			problems.push( `no re-point for D15 target "${ r.target }" (from ${ old })` );
			continue;
		}
		if ( keyOf( old ) === target.split( '#' )[ 0 ] ) {
			counts.skipped++; // A redirect to itself would loop.
			continue;
		}
		map.set( keyOf( old ), [ 301, target ] );
		counts[ 301 ]++;
	} else {
		counts.skipped++;
	}
}

const keys = [ ...map.keys() ].sort();
const lines = [
	'<?php',
	'/**',
	' * GENERATED by wordpress/tools/redirects/gen-redirect-map.mjs from research/redirects.csv',
	' * and wordpress/tools/redirects/repoint.csv. Do not edit by hand; edit the CSVs and re-run.',
	` * ${ counts[ 301 ] } redirects (301), ${ counts[ 410 ] } gone (410).`,
	' *',
	' * @package spokares-hardening',
	' */',
	'',
	"defined( 'ABSPATH' ) || exit;",
	'',
	'return array(',
	...keys.map( ( k ) => {
		const [ status, target ] = map.get( k );
		return `\t${ phpString( k ) } => array( ${ status }, ${ phpString( target ) } ),`;
	} ),
	');',
	'',
];
const out = lines.join( '\n' );

if ( problems.length ) {
	console.error( problems.join( '\n' ) );
}
if ( check ) {
	const current = fs.existsSync( outPath ) ? fs.readFileSync( outPath, 'utf8' ) : '';
	if ( current !== out ) {
		console.error( 'redirect-map.php is out of date: run node wordpress/tools/redirects/gen-redirect-map.mjs' );
		process.exit( 1 );
	}
	console.log( 'redirect-map.php is up to date.' );
	process.exit( problems.length ? 1 : 0 );
}
fs.writeFileSync( outPath, out );
console.log( `Wrote ${ path.relative( repo, outPath ) }: ${ counts[ 301 ] } × 301, ${ counts[ 410 ] } × 410, ${ counts.skipped } rows skipped (host, none, keep).` );
process.exit( problems.length ? 1 : 0 );
