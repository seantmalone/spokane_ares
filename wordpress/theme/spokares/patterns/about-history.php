<!-- /wp:heading -->

<!-- wp:paragraph {"className":"needs-verify"} -->
<p class="needs-verify">Our call sign honors Ira “Dean” Bula, W7GBU. For years he handed out technical wisdom and friendly advice from the counter at Northwest Electronics. Each morning he led an on-air round table on the repeater that now carries his call. Newly licensed hams found him there, and it became the 7:30 Bunch, which still meets weekday mornings. When the county retired the repeater’s old call sign, the Spokane County ARES-RACES Support Group applied for Dean’s call to inspire its members.</p>
<!-- /wp:paragraph -->

<!-- wp:quote {"className":"pullquote"} -->
<blockquote class="wp-block-quote pullquote"><!-- wp:paragraph -->
